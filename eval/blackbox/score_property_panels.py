#!/usr/bin/env python3
"""Scoring for the black-box property-conformance benchmark (written before any read was collected).

Inputs
  panels_P*.json                 generated by make_property_panels.py
  reads_llm_P*.json              {"<stay>" or "<stay>@<ladder>": [{"name":..., "probability":...}, ...]}  (LLM, blind)
  engine reads are computed here by running the frozen engine on the identical perturbed panels.

Metrics (identical for both systems)
  P2 units        : Jaccard of top-5 label-group sets between SI and conventional readings; label-level recall@5 change
  P3 presentation : same, shuffled + distractors vs original
  P4 monotonicity : fraction of ladders in which the best renal rank (AKI / renal impairment / CKD union) worsens at any step
  P5 absent       : fraction of panels in which the target group is still asserted at rank ≤ 5 after its defining
                    analyte was removed (unsupported assertion)
  P6 healthy      : fraction of healthy adults with ≥ 1 disease group asserted at rank ≤ 3
The conventional-unit LLM reading for P2/P3 is the original blind reading (B3/B4/B8); engine reference = frozen v7 output.
"""
from __future__ import annotations
import os, sys, json, gzip, ast, re, logging
logging.disable(logging.CRITICAL)
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, ROOT); sys.path.insert(0, os.path.join(ROOT, "eval", "realdata")); sys.path.insert(0, os.path.join(ROOT, "eval", "baselines"))
from eval_eicu import GROUPS  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__))
P = lambda x: ast.literal_eval(x) if isinstance(x, str) else x

# synonym map used for the LLM free-text names (same as b8_v7_cluster.SYN)
_src = open(os.path.join(ROOT, "eval/baselines/b8_v7_cluster.py")).read()
_ns = {}
exec(_src[_src.index("SYN"):_src.index("def llm_ranks")], _ns)
SYN = _ns["SYN"]
RENAL = {"acute_kidney_injury", "renal_impairment", "chronic_kidney_disease"}


def llm_groups(entries):
    gr = {}
    for rank, d in enumerate(entries, 1):
        nm = str(d.get("name", ""))
        for g, rx in SYN.items():
            if re.search(rx, nm, re.I):
                gr.setdefault(g, rank)
    return gr


def engine_groups(panel):
    import analyse_gidlines as ag
    E = engine_groups.E if hasattr(engine_groups, "E") else ag.ClinicalRuleEngine()
    engine_groups.E = E
    obs = {it["analyte"]: {"value": float(it["value"]), "unit": it["unit"]} for it in panel["panel"]}
    rep = E.interpret(obs, None, {"age_years": int(float(panel["age"])), "sex_at_birth": panel["sex"]}).to_dict()
    gr = {}
    for rank, d in enumerate(rep["differential_diagnosis"], 1):
        for g, (_, ents, _, _) in GROUPS.items():
            if d["disease_id"] in ents:
                gr.setdefault(g, rank)
    return gr


def top5(gr):
    return {g for g, r in gr.items() if r <= 5}


def jacc(a, b):
    return 1.0 if not a and not b else len(a & b) / len(a | b)


def load_reads(name):
    p = os.path.join(HERE, f"reads_llm_{name}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    rows = {str(r["stay"]): r for r in json.load(gzip.open(os.path.join(ROOT, "eval/results/eicu_demo/per_stay_v7.json.gz"), "rt"))}
    for r in rows.values():
        for k in ("gr", "coded", "labs"):
            r[k] = P(r[k])
    # original LLM readings
    _b = _src.split("def main():")[0].replace('json.load(open(os.path.join(R, "b8_blind_panels_n240.json")))', 'json.load(gzip.open(os.path.join(R, "b8_blind_panels_n240.json.gz"),"rt"))')
    ns = {"__file__": os.path.join(ROOT, "eval/baselines/b8_v7_cluster.py")}
    exec(compile(_b, "b8", "exec"), ns)
    llm0 = {str(s[0]): llm_groups(s[3]) for s in ns["stays"]}
    out = ["# Black-box property conformance — frozen engine v7 vs unnamed frontier LLM (identical perturbed panels)", ""]
    res = {}

    for name in ("P2_units", "P3_presentation"):
        panels = json.load(open(os.path.join(HERE, f"panels_{name}.json")))
        reads = load_reads(name)
        je, jl, de, dl, n = [], [], [], [], 0
        for p in panels:
            s = p["stay"]; eg = engine_groups(p); eg0 = rows[s]["gr"]
            je.append(jacc(top5(eg), top5(eg0)))
            lab = [g for g in rows[s]["coded"] if g in GROUPS and any(k in rows[s]["labs"] for k in GROUPS[g][2])]
            de.append(sum(eg.get(g, 99) <= 5 for g in lab) - sum(eg0.get(g, 99) <= 5 for g in lab))
            if reads and s in reads:
                lg = llm_groups(reads[s]); lg0 = llm0[s]
                jl.append(jacc(top5(lg), top5(lg0))); dl.append(sum(lg.get(g, 99) <= 5 for g in lab) - sum(lg0.get(g, 99) <= 5 for g in lab)); n += 1
        res[name] = {"engine_jaccard": sum(je) / len(je), "engine_identical": sum(j == 1.0 for j in je), "n_engine": len(je),
                     "llm_jaccard": (sum(jl) / n) if n else None, "llm_identical": sum(j == 1.0 for j in jl), "n_llm": n,
                     "engine_label_delta": sum(de), "llm_label_delta": sum(dl)}

    panels = json.load(open(os.path.join(HERE, "panels_P4_monotonic.json"))); reads = load_reads("P4_monotonic")
    ladders = {}
    for p in panels:
        ladders.setdefault(p["stay"], []).append(p)
    ve = vl = ne = nl = 0
    for s, ps in ladders.items():
        ps.sort(key=lambda d: d["ladder"])
        er = [min([engine_groups(p).get(g, 99) for g in RENAL]) for p in ps]
        ne += 1; ve += int(any(er[i + 1] > er[i] for i in range(2)))
        if reads and all(f"{s}@{p['ladder']}" in reads for p in ps):
            lr = [min([llm_groups(reads[f"{s}@{p['ladder']}"]).get(g, 99) for g in RENAL]) for p in ps]
            nl += 1; vl += int(any(lr[i + 1] > lr[i] for i in range(2)))
    res["P4_monotonic"] = {"engine_violations": ve, "n_engine": ne, "llm_violations": vl, "n_llm": nl}

    panels = json.load(open(os.path.join(HERE, "panels_P5_absent.json"))); reads = load_reads("P5_absent")
    ue = ul = ne = nl = 0; detail = []
    for p in panels:
        s = p["stay"]; g = p["target_group"]
        eg = engine_groups(p); ne += 1; e_un = eg.get(g, 99) <= 5; ue += int(e_un)
        l_un = None
        if reads and s in reads:
            lg = llm_groups(reads[s]); nl += 1; l_un = lg.get(g, 99) <= 5; ul += int(l_un)
        detail.append((s, g, p["removed_analyte"], e_un, l_un))
    res["P5_absent"] = {"engine_unsupported": ue, "n_engine": ne, "llm_unsupported": ul, "n_llm": nl}

    p6 = os.path.join(HERE, "panels_P6_healthy.json"); reads = load_reads("P6_healthy")
    if os.path.exists(p6) and json.load(open(p6)):
        panels = json.load(open(p6)); fe = fl = nl = 0
        for p in panels:
            eg = engine_groups(p); fe += int(any(r <= 3 for r in eg.values()))
            if reads and p["stay"] in reads:
                nl += 1; fl += int(any(r <= 3 for r in llm_groups(reads[p["stay"]]).values()))
        res["P6_healthy"] = {"engine_false_alarm": fe, "n_engine": len(panels), "llm_false_alarm": fl, "n_llm": nl}

    out += ["| property | engine | LLM |", "|---|---|---|"]
    for k, v in res.items():
        if k.startswith("P2") or k.startswith("P3"):
            out.append(f"| {k}: top-5 Jaccard vs original (identical/n) | {v['engine_jaccard']:.2f} ({v['engine_identical']}/{v['n_engine']}); label Δ {v['engine_label_delta']:+d} | "
                       + (f"{v['llm_jaccard']:.2f} ({v['llm_identical']}/{v['n_llm']}); label Δ {v['llm_label_delta']:+d}" if v["n_llm"] else "pending"))
        elif k == "P4_monotonic":
            out.append(f"| P4 monotonicity violations / ladders | {v['engine_violations']}/{v['n_engine']} | {v['llm_violations']}/{v['n_llm']} |")
        elif k == "P5_absent":
            out.append(f"| P5 unsupported assertions (target still at rank ≤ 5 without its analyte) | {v['engine_unsupported']}/{v['n_engine']} | {v['llm_unsupported']}/{v['n_llm']} |")
        else:
            out.append(f"| P6 healthy adults with ≥ 1 disease at rank ≤ 3 | {v['engine_false_alarm']}/{v['n_engine']} | {v['llm_false_alarm']}/{v['n_llm']} |")
    out += ["", "## P5 detail (stay, target, removed analyte, engine unsupported, LLM unsupported)", ""]
    out += [f"- {d}" for d in detail]
    txt = "\n".join(out); print(txt)
    open(os.path.join(HERE, "RESULTS.md"), "w").write(txt + "\n")
    json.dump(res, open(os.path.join(HERE, "results.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
